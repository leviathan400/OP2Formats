import json,sys
t=json.load(open(sys.argv[1]))
BASE=101
def fmt(r): return '['+', '.join('u16::MAX' if v is None else str(v) for v in r)+']'
veh=[];bld=[]
for n,r in t.items():
    s={int(k,16):v for k,v in r['stores'].items()}
    if n=='SCAT': continue
    if 0x24c in s:
        out={}
        for base,col in ((0x24c,'eden'),(0x34c,'plymouth')):
            rows=[]
            for st in range(4):
                row=[s.get(base+4*(st*16+d)) for d in range(16)]
                rows.append([None if v is None else v-BASE for v in row])
            while rows and not any(rows[-1]): rows.pop()
            out[col]=rows
        veh.append((n,r['init'],out))
    elif 0x1f0 in s and any(0x250<=k<0x2a0 for k in s):
        e=[s.get(0x250+4*i) for i in range(10)]; p=[s.get(0x278+4*i) for i in range(10)]
        f=lambda v:fmt([None if x is None or x==0 else x-BASE for x in v])
        b={int(k,16):v for k,v in r.get('bytes',{}).items()}
        bld.append((n,r['init'],f(e),f(p),f'[{b.get(0x2a6,0)}, {b.get(0x2a7,0)}]'))
print('// @generated by crates/op2-formats/scripts/unit_anims/extract.sh from the installed (GOG + OPU) Outpost2.exe.')
print('// Values are op2_art.prt animation indices (game animation id - 101); u16::MAX = no entry.\n')
print('static VEHICLES: &[VehicleArt] = &[')
for n,init,o in veh:
    print(f'    VehicleArt {{\n        code: "{n}",\n        init: {init},')
    for col in ('eden','plymouth'):
        print(f'        {col}: &[' + ', '.join(fmt(r) for r in o[col]) + '],')
    print('    },')
print('];\n')
print('static BUILDINGS: &[BuildingArt] = &[')
for n,init,e,p,amb in bld:
    print(f'    BuildingArt {{ code: "{n}", init: {init}, eden: {e}, plymouth: {p}, ambient: {amb} }},')
print('];')
tj=json.load(open(sys.argv[2]))
CODES={'AcidCloud':'ACID','BFG':'BFG','EMP':'EMP','ESG':'SPAM','Laser':'LASER','Microwave':'MICROWAVE','RailGun':'RAIL_GUN','RPG':'CANNON','Starflare':'SELF_DESTRUCT','StarflareGP':'SELF_DESTRUCT','Stickyfoam':'FOAM','Supernova':'SELF_DESTRUCT_ADV','SupernovaGP':'SELF_DESTRUCT_ADV','ThorsHammer':'THORS_HAMMER'}
merged={}
for cls,fns in tj.items():
    for kind,v in fns.items():
        if v['tables']: tabs=v['tables']
        elif v['imm']: tabs=[[v['imm'][0]]*16]+([[v['imm'][1]]*16] if len(v['imm'])>1 else [])
        else: continue
        # Two tables: the first is used when the owner's flag tested is set (see units.rs).
        merged.setdefault(CODES[cls],{})[kind]=(v['addr'],tabs)
print('\nstatic TURRETS: &[TurretArt] = &[')
for code,k in merged.items():
    print(f'    TurretArt {{\n        code: "{code}",')
    for kind in ('Lynx','Panther','Tiger','GuardPost'):
        if kind not in k: print(f'        {kind.lower().replace("guardpost","guard_post")}: None,'); continue
        addr,tabs=k[kind]
        a=tabs[0]; b=tabs[1] if len(tabs)>1 else tabs[0]
        print(f'        {kind.lower().replace("guardpost","guard_post")}: Some(TurretSet {{ select: {addr}, a: {fmt(a)}, b: {fmt(b)} }}),')
    print('    },')
print('];')
